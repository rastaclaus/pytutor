"""Упражнение 16. Политики вытеснения: FIFO / LRU / LFU. Уровень 6.

Кэши ограниченного размера различаются политикой вытеснения:

* **FIFO** — вытесняется самый старый по времени вставки
  (``OrderedDict.popitem(last=False)``); ``get`` порядок не меняет;
* **LRU** — вытесняется наименее недавно использованный (``move_to_end`` на
  каждом обращении, включая обновление значения);
* **LFU** — вытесняется наименее часто используемый (частоту считаем через
  ``Counter``); при равенстве частот вытесняется более старый ключ.

Реализуйте три класса кэшей с одинаковым интерфейсом: ``get``/``put``/``__len__``.

Тонкости, на которых чаще всего ошибаются:

* ``put`` для **существующего** ключа не должен вытеснять ничего — меняется
  только значение (и, для LRU/LFU, обновляется «свежесть»/частота);
* вытеснение делается **до** вставки нового ключа, иначе кэш на миг превысит
  ёмкость;
* ``get`` промаха возвращает ``None`` и **не** увеличивает частоту: иначе
  вымышленный ключ влиял бы на статистику.

Тексты ошибок: для неположительной ёмкости нужно ``ValueError`` со словом
``capacity`` (например, ``"capacity должно быть >= 1"``).
"""

from __future__ import annotations

from collections import Counter, OrderedDict


class FIFOCache:
    """Кэш, вытесняющий самый старый по вставке ключ."""

    def __init__(self, capacity: int) -> None:
        """Создать кэш на ``capacity`` элементов (``capacity >= 1``).

        ``FIFOCache(0)`` и ``FIFOCache(-1)`` -> ``ValueError`` (в сообщении есть
        ``capacity``);
        ``len(FIFOCache(2)) == 0``.

        Подсказка: проверка ёмкости — первым делом, до создания ``_data``.
        """
        raise NotImplementedError

    def get(self, key: str) -> int | None:
        """Вернуть значение (без изменения порядка).

        после ``put("a", 1)``: ``get("a")`` -> ``1``;
        ``get("missing")`` -> ``None``;
        порядок вставки от ``get`` не меняется, поэтому ``get`` не влияет на
        то, кто будет вытеснен.

        Подсказка: ``self._data.get(key)``. ``move_to_end`` здесь был бы
        ошибкой — это уже LRU.
        """
        raise NotImplementedError

    def put(self, key: str, value: int) -> None:
        """Записать пару; при переполнении вытеснить самый старый ключ.

        ``cache = FIFOCache(2)``: после ``put("a", 1)``, ``put("b", 2)`` и
        ``get("a")`` вызов ``put("c", 3)`` вытеснит ``a``, потому что ``get``
        порядок не освежил;
        ``put`` существующего ключа обновляет значение и не вытесняет ничего;
        после переполнения ``len(cache) == capacity``.

        Подсказка: ``if len(self._data) >= self.capacity and key not in
        self._data: self._data.popitem(last=False)``, затем присваивание.
        """
        raise NotImplementedError

    def __len__(self) -> int:
        """Число записей.

        ``len(FIFOCache(2))`` -> ``0``;
        после двух ``put`` -> ``2``;
        после трёх ``put`` при ёмкости 2 -> ``2``.

        Подсказка: ``len(self._data)``.
        """
        raise NotImplementedError


class LRUCache:
    """Кэш, вытесняющий наименее недавно использованный ключ."""

    def __init__(self, capacity: int) -> None:
        """Создать кэш на ``capacity`` элементов (``capacity >= 1``).

        ``LRUCache(0)`` -> ``ValueError`` (в сообщении есть ``capacity``).

        Подсказка: как в ``FIFOCache``, но политика другая — хранилище то же,
        ``OrderedDict``.
        """
        raise NotImplementedError

    def get(self, key: str) -> int | None:
        """Вернуть значение, освежив ключ (или ``None``).

        ``cache = LRUCache(2)``: после ``put("a", 1)``, ``put("b", 2)`` и
        ``get("a")`` вызов ``put("c", 3)`` вытеснит ``b``;
        ``get("missing")`` -> ``None`` и порядок не меняется.

        Подсказка: проверка ``key in self._data``, затем ``move_to_end(key)``.
        """
        raise NotImplementedError

    def put(self, key: str, value: int) -> None:
        """Записать пару; при переполнении вытеснить LRU-ключ.

        ``put`` существующего ключа обновляет значение и освежает ключ;
        при переполнении вытесняется ключ из начала ``OrderedDict``.

        Подсказка: ``move_to_end`` для существующего ключа, присваивание, затем
        ``if len(self._data) > self.capacity: popitem(last=False)``.
        """
        raise NotImplementedError

    def __len__(self) -> int:
        """Число записей.

        ``len(LRUCache(2))`` -> ``0``;
        после трёх ``put`` при ёмкости 2 -> ``2``.

        Подсказка: ``len(self._data)``.
        """
        raise NotImplementedError


class LFUCache:
    """Кэш, вытесняющий наименее часто используемый ключ.

    Частота считается обращениями ``get``/``put``. При равенстве частот
    вытесняется более старый ключ.

    Две частоты различаются: ровно вставленный ключ считается одним обращением
    (частота 1), а промах ``get`` не считается вовсе.
    """

    def __init__(self, capacity: int) -> None:
        """Создать кэш на ``capacity`` элементов (``capacity >= 1``).

        ``LFUCache(0)`` -> ``ValueError`` (в сообщении есть ``capacity``).

        Подсказка: понадобятся два хранилища — ``OrderedDict`` для значений и
        ``Counter`` для частот.
        """
        raise NotImplementedError

    def get(self, key: str) -> int | None:
        """Вернуть значение, увеличив частоту обращения (или ``None``).

        ``cache = LFUCache(2)``: после ``put("a", 1)``, ``put("b", 2)`` и двух
        ``get("a")`` вызов ``put("c", 3)`` вытеснит ``b`` — у него частота 1
        против 3 у ``a``;
        ``get("missing")`` -> ``None``, частота не увеличивается.

        Подсказка: проверка наличия, ``self._freq[key] += 1``, затем
        ``move_to_end`` (для развязки ничьих по возрасту) и возврат значения.
        """
        raise NotImplementedError

    def put(self, key: str, value: int) -> None:
        """Записать пару; при переполнении вытеснить LFU-ключ.

        ``put`` существующего ключа обновляет значение **и** увеличивает
        частоту;
        новый ключ при переполнении сначала вытесняет жертву, затем получает
        частоту 1.

        Подсказка: жертва — ``min(self._data, key=lambda key: (self._freq[key],
        list(self._data).index(key)))``: первым идёт меньшая частота, вторым —
        более ранняя позиция в ``OrderedDict``. Не забудьте удалить жертву из
        обоих хранилищ.
        """
        raise NotImplementedError

    def __len__(self) -> int:
        """Число записей.

        ``len(LFUCache(2))`` -> ``0``;
        после трёх ``put`` при ёмкости 2 -> ``2``.

        Подсказка: ``len(self._data)``.
        """
        raise NotImplementedError
