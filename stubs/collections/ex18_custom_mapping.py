"""Упражнение 18. ``collections.abc.MutableMapping`` — свой словарь с нуля. Уровень 7.

Чтобы получить полноценный изменяемый словарь, достаточно реализовать пять
методов ``MutableMapping``: ``__getitem__``, ``__setitem__``, ``__delitem__``,
``__iter__`` и ``__len__``. Всё остальное (``get``, ``keys``, ``pop``, ``in``,
``items``, ``update``) абстрактный класс построит сам поверх них.

Это самый честный способ сделать «свой» словарь: полный контроль над хранилищем.

Что важно понимать про наследование от ``MutableMapping``:

* методы-обёртки делегируют в ваши пять методов, поэтому ``dict(d.items())``,
  ``d.get(...)`` и ``d.pop(...)`` работают автоматически;
* ``__contains__`` по умолчанию реализован через ``__getitem__``, значит
  **попадёт в ваш журнал/счётчик**, если не переопределить его;
* ``pop`` использует и ``__getitem__``, и ``__delitem__`` — тоже даёт записи в
  журнале.

Здесь мы делаем логгирующий словарь, который записывает все операции, и словарь,
который считает обращения по ключам.

Формат записей журнала: ``"get:key"``, ``"set:key=value"``, ``"del:key"``.

Термины, на которые ссылаются условия:

* **обращение** — вызов ``__getitem__`` (в том числе через ``get``/``in``);
* **журнал** — список строк в порядке выполнения операций.
"""

from __future__ import annotations

from collections.abc import Iterator, MutableMapping


class LoggingDict(MutableMapping[str, int]):
    """Словарь, который записывает все операции чтения и записи.

    Журнал хранится в атрибуте ``log`` (список строк вида ``"get:key"``,
    ``"set:key=value"``, ``"del:key"``).

    Реализуйте пять обязательных методов; остальное сделает ``MutableMapping``.

    Подсказка: хранилище — обычный ``dict`` в приватном атрибуте (например
    ``self._data``), журнал — список. Публичный атрибут ``log`` тест читает
    напрямую.
    """

    def __init__(self) -> None:
        """Создать пустой словарь с журналом.

        ``len(LoggingDict())`` -> ``0``;
        ``LoggingDict().log`` -> ``[]``.

        Подсказка: два пустых контейнера — ``_data`` и ``log``. Не используйте
        изменяемый аргумент по умолчанию, инициализируйте в теле.
        """
        raise NotImplementedError

    def __getitem__(self, key: str) -> int:
        """Вернуть значение, записав в журнал ``get:key``.

        ``d["x"] = 10`` даёт запись ``"set:x=10"``, затем ``d["x"]`` -> ``10`` и
        запись ``"get:x"``;
        ``d["nope"]`` -> ``KeyError``, но запись ``"get:nope"`` **уже
        добавлена** — журналируется сама попытка чтения.

        Подсказка: сначала ``self.log.append(f"get:{key}")``, потом доставайте
        значение. Так исключение не помешает записи.
        """
        raise NotImplementedError

    def __setitem__(self, key: str, value: int) -> None:
        """Записать значение, записав в журнал ``set:key=value``.

        ``d["a"] = 1`` -> в журнале ``"set:a=1"``;
        повторная запись ``d["a"] = 2`` добавляет новую строку, а не заменяет
        старую;
        ``len(d)`` после двух записей одного ключа равно ``1``.

        Подсказка: формат строки строго ``f"set:{key}={value}"`` — тест
        сравнивает журнал целиком.
        """
        raise NotImplementedError

    def __delitem__(self, key: str) -> None:
        """Удалить ключ, записав в журнал ``del:key``.

        ``del d["a"]`` -> запись ``"del:a"``;
        ``del d["nope"]`` -> ``KeyError`` (сначала идёт запись, потом ошибка);
        после удаления ключа ``"a" not in d`` -> ``True``.

        Подсказка: ``self.log.append(f"del:{key}")`` и затем ``del
        self._data[key]``.
        """
        raise NotImplementedError

    def __iter__(self) -> Iterator[str]:
        """Итерация по ключам.

        ``dict(d.items())`` -> обычный словарь со всеми парами;
        ``list(d)`` возвращает ключи в порядке вставки;
        итерация **не** добавляет записей в журнал.

        Подсказка: ``iter(self._data)``. Если вернуть сам ``self._data``,
        контракт ``__iter__`` (объект-итератор) нарушится.
        """
        raise NotImplementedError

    def __len__(self) -> int:
        """Число записей.

        ``len(LoggingDict())`` -> ``0``;
        после двух ``set`` разных ключей -> ``2``;
        после ``del`` одного из них -> ``1``.

        Подсказка: ``len(self._data)``. Не считайте журнал: его длина отражает
        операции, а не ключи.
        """
        raise NotImplementedError


class AccessCountingDict(MutableMapping[str, int]):
    """Словарь, который считает обращения к ключам.

    Счётчики обращений хранятся в ``AccessCountingDict.access`` (обычный словарь:
    ключ -> сколько раз к нему обратились через ``get``/``__getitem__``).

    Подсказка: данные — в ``_data``, счётчики — в публичном ``access``.
    Удобнее всего начать ``self._data = dict(initial or {})``: так
    ``initial=None`` и ``initial={}`` обрабатываются одинаково.
    """

    def __init__(self, initial: dict[str, int] | None = None) -> None:
        """Создать словарь, заполнив из ``initial`` (если дан).

        ``AccessCountingDict({"a": 1})["a"]`` -> ``1``;
        ``len(AccessCountingDict())`` -> ``0``;
        ``AccessCountingDict().access`` -> ``{}`` — начальное заполнение
        обращениями не считается.

        Подсказка: ``dict(initial or {})``. Не присваивайте
        ``self._data = initial``: тогда внешний словарь окажется связанным с
        объектом.
        """
        raise NotImplementedError

    def __getitem__(self, key: str) -> int:
        """Вернуть значение и увеличить счётчик обращений к ключу.

        ``d = AccessCountingDict({"a": 1, "b": 2})``: после двух чтений ``a`` и
        одного ``b`` ``d.access == {"a": 2, "b": 1}``;
        ``d["missing"]`` -> ``KeyError``; счётчик при этом **не** создаётся.

        Подсказка: сначала убедитесь, что ключ есть (или обратитесь к
        ``self._data[key]``, поймав исключение), и только потом увеличивайте
        счётчик — иначе промах добавит запись.
        """
        raise NotImplementedError

    def __setitem__(self, key: str, value: int) -> None:
        """Записать значение (обращения не считаются).

        ``d["c"] = 3`` не меняет ``d.access``;
        после записи ``d["c"]`` -> ``3`` и ``d.access["c"] == 1``.

        Подсказка: только ``self._data[key] = value``. Если бы здесь
        увеличивался счётчик, ``update``/``setdefault`` из ``MutableMapping``
        исказили бы статистику.
        """
        raise NotImplementedError

    def __delitem__(self, key: str) -> None:
        """Удалить ключ (и его счётчик обращений).

        ``d["a"]``, затем ``del d["a"]``: ``"a" not in d.access`` и
        ``len(d) == 0``;
        ``del d["nope"]`` -> ``KeyError``.

        Подсказка: удалите из ``_data`` и сделайте ``self.access.pop(key,
        None)`` — именно с ``None``, потому что ключ мог ни разу не читаться.
        """
        raise NotImplementedError

    def __iter__(self) -> Iterator[str]:
        """Итерация по ключам.

        ``list(d)`` — ключи в порядке вставки;
        итерация не увеличивает счётчики.

        Подсказка: ``iter(self._data)``.
        """
        raise NotImplementedError

    def __len__(self) -> int:
        """Число записей.

        ``len(AccessCountingDict({"a": 1, "b": 2}))`` -> ``2``;
        после ``del`` одного ключа -> ``1``.

        Подсказка: ``len(self._data)``.
        """
        raise NotImplementedError

    def most_accessed(self, n: int) -> list[tuple[str, int]]:
        """Вернуть ``n`` самых часто запрашиваемых ключей с числом обращений.

        ``d`` с обращениями ``a: 2``, ``b: 1``: ``most_accessed(1)`` ->
        ``[("a", 2)]``, ``most_accessed(5)`` -> ``[("a", 2), ("b", 1)]``;
        ``most_accessed(0)`` -> ``[]``;
        у словаря без обращений — ``[]``.

        Сортировка: по убыванию счётчика, при равенстве — по возрастанию ключа.
        Ключи без обращений в результат не попадают (их нет в ``access``).

        Подсказка: ``sorted(self.access.items(), key=lambda item: (-item[1],
        item[0]))[:n]``. Ровно та же схема, что в ``top_n`` из упражнения 10.
        """
        raise NotImplementedError
