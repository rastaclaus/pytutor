"""Упражнение 10. Top-N с развязкой ничьих. Уровень 4.

``Counter.most_common(n)`` возвращает ``n`` самых частых элементов, но при
равных частотах порядок среди них не гарантирован (на практике это порядок
первого вхождения, но полагаться на это нельзя). Во многих задачах нужен
детерминированный порядок: при равенстве частот сортируем по ключу.

Задача — реализовать выборку top-N и bottom-N с чётким правилом развязки.

Правило во всех функциях: сортировка идёт по кортежу-ключу, где первым идёт
основной критерий, вторым — развязка по имени.

* top-N: ``key = (-частота, ключ)`` — частота по убыванию, ключ по возрастанию;
* bottom-N: ``key = (частота, ключ)`` — частота по возрастанию, ключ по
  возрастанию;
* by key: ``key = ключ`` — только имя.

Тексты ошибок: ``n < 0`` — ``ValueError`` со словом ``n`` (например,
``"n должно быть >= 0"``). Срез ``[:n]`` сам по себе отрицательный ``n`` не
отклоняет: ``items[:-1]`` отбросит последний элемент и вернёт «почти всё».
"""

