"""Упражнение 6. Декораторы с аргументами. Уровень 4.

Декоратор с аргументами — это функция, которая возвращает декоратор
(«фабрика декораторов»). Не забудьте про ``functools.wraps``, чтобы сохранить
метаданные обёрнутой функции.

Схема из трёх уровней: ``repeat(3)`` -> декоратор -> обёрнутая функция.

Реализуйте:

* ``repeat(times)`` — вызывает функцию ``times`` раз и возвращает список
  результатов;
* ``retry(times, exceptions)`` — делает до ``times`` попыток вызова; повторяет
  только при исключениях из ``exceptions``; если все попытки неудачны —
  пробрасывает последнее исключение.

Тексты ошибок: ``retry(0)`` и ``retry(-1)`` должны бросать ``ValueError``
сразу при создании декоратора (в сообщении есть ``times``), не дожидаясь вызова
функции.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Any, TypeVar

F = TypeVar("F", bound=Callable[..., Any])


def repeat(times: int) -> Callable[[F], F]:
    """Вернуть декоратор, вызывающий функцию ``times`` раз.

    ``@repeat(3)`` над функцией, возвращающей ``1, 2, 3`` по очереди, даёт
    ``[1, 2, 3]``;
    ``@repeat(0)`` даёт ``[]`` — функция не вызывается ни разу;
    ``@repeat(1)`` даёт список из одного результата;
    ``times < 0`` — тоже пустой список (повторов не меньше нуля).

    Метаданные сохраняются: ``__name__`` и ``__doc__`` обёрнутой функции
    остаются её собственными.

    Подсказка: ``[func(*args, **kwargs) for _ in range(max(times, 0))]``
    внутри ``wrapper``, а на ``wrapper`` — ``@wraps(func)``.
    """
    raise NotImplementedError


def retry(times: int, exceptions: tuple[type[BaseException], ...] = (Exception,)) -> Callable[[F], F]:
    """Вернуть декоратор с повторами при ошибках.

    Максимум ``times`` попыток (``times >= 1``);
    ``@retry(3)`` над функцией, падающей дважды, вернёт результат на третьей
    попытке — всего 3 вызова;
    ``@retry(2, exceptions=(ValueError,))`` над всегда падающей ``ValueError``
    сделает ровно 2 вызова и пробросит последнюю ошибку;
    ``@retry(3, exceptions=(ValueError,))`` над функцией, бросающей ``KeyError``,
    вызовет её один раз и пробросит ``KeyError`` сразу — исключения не из
    ``exceptions`` не повторяются;
    ``retry(0)`` -> ``ValueError`` (в сообщении есть ``times``).

    Если все попытки провалились, пробрасывается последнее исключение — новое
    не создаётся и не оборачивается.

    Подсказка: цикл ``range(times)`` с ``try/except exceptions``; на последней
    попытке просто дайте исключению уйти (или сохраните его и бросьте после
    цикла). Один и тот же ``except`` не должен ловить ``BaseException`` целиком.
    """
