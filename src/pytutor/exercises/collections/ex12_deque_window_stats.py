"""Упражнение 12. Скользящее окно: статистика в потоке. Уровень 5.

Когда данные приходят потоком и нужно считать статистику по последним ``N``
элементам, идеальный инструмент — ``deque(maxlen=N)``: добавление нового элемента
автоматически вытесняет самый старый, и окно всегда имеет ровно ``N`` элементов
(после разогрева).

Здесь мы строим «живые» скользящие статистики: среднее, минимум и максимум, а
также отклонение от среднего. Все вычисления — в потоке, без материализации
всего входа.

Четыре правила, общие для всех функций:

* результат — **генератор**: значения появляются по мере поступления входа,
  поэтому имена функций возвращают ``Iterator``, а не список;
* пока в окне меньше ``size`` элементов, ничего не выдаётся — окно «нагревается»;
* длина результата — ``max(0, len(values) - size + 1)``;
* ``size <= 0`` — ``ValueError``. Важная тонкость: тело генератора не
  выполняется до первого ``next``, поэтому проверку нужно ставить **внутрь**
  функции-генератора до цикла, иначе исключение «потеряется» до момента
  итерации. Тесты оборачивают вызов в ``list(...)``, так что ошибка проявится
  правильно.

Термины, на которые ссылаются условия:

* **окно** — последние ``size`` просмотренных элементов;
* **отклонение от среднего** — ``value - sum(window) / size`` для текущего
  значения, уже включённого в окно.
"""

from __future__ import annotations

from collections import deque
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Iterable, Iterator


def moving_average(values: Iterable[float], size: int) -> Iterator[float]:
    """Генератор скользящих средних по последним ``size`` элементам.

    ``list(moving_average([1, 2, 3, 4], 2))`` -> ``[1.5, 2.5, 3.5]`` — три окна
    по два элемента;
    ``list(moving_average([1, 2], 5))`` -> ``[]`` — окно не набралось;
    ``list(moving_average([], 2))`` -> ``[]``;
    ``list(moving_average([1], 0))`` и ``list(moving_average([1], -1))`` ->
    ``ValueError`` (в сообщении есть ``size``).

    Результат — ``float``: ``sum`` целых чисел, делённая на ``size``, даёт
    ``float`` даже когда делится нацело.

    Подсказка: ``deque(maxlen=size)``, на каждом элементе ``append`` и выдача
    только при ``len(window) == size``. Проверка ``size <= 0`` — в начале тела,
    до создания очереди.
    """
    raise NotImplementedError


def moving_max(values: Iterable[int], size: int) -> Iterator[int]:
    """Генератор максимумов в каждом окне из последних ``size`` элементов.

    ``list(moving_max([1, 3, 2, 5], 2))`` -> ``[3, 3, 5]`` — окна ``(1,3)``,
    ``(3,2)``, ``(2,5)``;
    ``list(moving_max([1], 1))`` -> ``[1]`` — размер окна 1 даёт сам элемент;
    ``list(moving_max([1, 2], 3))`` -> ``[]``;
    ``list(moving_max([], 0))`` -> ``ValueError`` (в сообщении есть ``size``).

    Подсказка: тот же каркас, что и у ``moving_average``, но в выдаче
    ``max(window)``.
    """
    raise NotImplementedError


def moving_min(values: Iterable[int], size: int) -> Iterator[int]:
    """Генератор минимумов в каждом окне из последних ``size`` элементов.

    ``list(moving_min([3, 1, 2, 5], 2))`` -> ``[1, 1, 2]``;
    ``list(moving_min([1], 1))`` -> ``[1]``;
    ``list(moving_min([1, 2], 3))`` -> ``[]``;
    ``list(moving_min([], -1))`` -> ``ValueError`` (в сообщении есть ``size``).

    Подсказка: ``min(window)`` в выдаче. Каркас не меняется — если вынесли
    общий помощник, ``moving_max`` и ``moving_min`` станут однострочными.
    """
