def deviation_from_mean(values: Iterable[float], size: int) -> Iterator[float]:
    """Генератор отклонений текущего элемента от среднего по окну.

    Для каждого элемента, начиная с ``size``-го, вернуть
    ``элемент - среднее_окна``.

    ``list(deviation_from_mean([1, 3, 5, 7], 2))`` -> ``[1.0, 1.0, 1.0]``:
    окна ``(1,3)``, ``(3,5)``, ``(5,7)`` — текущий элемент всегда на 1 больше
    среднего;
    ``list(deviation_from_mean([1, 2], 5))`` -> ``[]``;
    ``list(deviation_from_mean([1], 0))`` -> ``ValueError`` (в сообщении есть
    ``size``).

    Порядок операций важен: элемент сначала попадает в окно, и только потом
    считается среднее — поэтому ``value`` уже входит в сумму. Для окна чётной
    длины и ``value = 4`` при среднем ``2.5`` отклонение будет ``1.5``.

    Подсказка: ``value - sum(window) / size`` внутри проверки
    ``len(window) == size``.
    """
