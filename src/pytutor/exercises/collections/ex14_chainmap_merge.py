"""Упражнение 14. Слияние ``ChainMap``: «плоский» словарь и отчёт. Уровень 6.

``ChainMap`` — представление «на лету», без копирования. Но часто нужен
материализованный результат: «плоский» словарь, где конфликты разрешены в
пользу приоритетного слоя, и отчёт о том, из какого слоя пришёл каждый ключ.

В этом упражнении мы учимся «вытаскивать» данные из ``ChainMap`` в разные формы.

Важно различать два порядка обхода:

* **по ключам** (``dict(cm)``, поиск значения) — конфликт решается в пользу
  первого слоя, поэтому «плоский» словарь содержит значение верхнего слоя;
* **по слоям** (``cm.maps``) — в каждом слое ключи идут в своём порядке
  вставки. Для отчёта о слоях и для записи «во все слои» нужен именно он.

Термины, на которые ссылаются условия:

* **номер слоя** — индекс в ``cm.maps``, 0 — самый приоритетный;
* **конфликт** — ключ, который присутствует больше чем в одном слое;
* **слияние** — построение нового обычного ``dict``, не связанного со слоями.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections import ChainMap
    from collections.abc import Iterable


def flatten(cm: ChainMap[str, int]) -> dict[str, int]:
    """Слить все слои в обычный словарь.

    Приоритет — у первого слоя (как при обычном поиске в ``ChainMap``).

    ``flatten(ChainMap({"a": 1}, {"a": 2, "b": 3}))`` -> ``{"a": 1, "b": 3}``;
    ``flatten(ChainMap())`` -> ``{}``;
    ``flatten(ChainMap({"x": 0}, {"y": 1}))`` -> ``{"x": 0, "y": 1}`` — ноль
    остаётся значением.

    Подсказка: ``dict(cm)``. Результат — копия: изменение словаря не затронет
    слои.
    """
    raise NotImplementedError


def source_report(cm: ChainMap[str, int]) -> dict[str, int]:
    """Вернуть отчёт: ключ -> номер слоя, где он найден.

    Номера начинаются с 0 (самый приоритетный слой). Если ключ есть в нескольких
    слоях — указать первый.

    ``source_report(ChainMap({"a": 1}, {"a": 2, "b": 3}))`` ->
    ``{"a": 0, "b": 1}``;
    ``source_report(ChainMap())`` -> ``{}``;
    ``source_report(ChainMap({"a": 1}, {"b": 2}, {"c": 3}))`` ->
    ``{"a": 0, "b": 1, "c": 2}``.

    Порядок ключей в отчёте — порядок первого появления при обходе слоёв
    сверху вниз.

    Подсказка: ``enumerate(cm.maps)`` и «добавить, только если ключа ещё нет»
    (``if key not in report``). Порядок обхода слоёв гарантирует, что первым
    запишется именно приоритетный номер.
    """
    raise NotImplementedError


def conflict_keys(cm: ChainMap[str, int]) -> list[str]:
    """Вернуть ключи, которые есть более чем в одном слое.

    Порядок — как в ``flatten`` (первое появление ключа при обходе слоёв
    сверху вниз).

    ``conflict_keys(ChainMap({"a": 1, "c": 4}, {"a": 2, "b": 3}, {"b": 5, "c":
    6}))`` -> ``["a", "b", "c"]`` (как множество);
    ``conflict_keys(ChainMap({"a": 1}, {"b": 2}))`` -> ``[]`` — пересечений нет;
    ``conflict_keys(ChainMap())`` -> ``[]``.

    Ключ попадает в результат **один раз**, даже если он есть во всех трёх
    слоях.

    Подсказка: держите ``set`` уже виденных ключей и список конфликтов;
    добавляйте в конфликты только при повторе и только если его там ещё нет.
    """
