def update_all_layers(cm: ChainMap[str, int], key: str, value: int) -> ChainMap[str, int]:
    """Записать ``key=value`` во все слои, где ключ уже существует.

    В слоях, где ключа нет, ничего не менять. Вернуть ``cm``.

    ``first = {"a": 1}``, ``second = {"a": 2, "b": 3}``, ``cm = ChainMap(first,
    second)``: после ``update_all_layers(cm, "a", 99)`` результат ``is cm``,
    ``first["a"] == 99``, ``second["a"] == 99``, а ``second["b"]`` остался ``3``;
    ключ, которого нет ни в одном слое, **не добавляется**;
    ``cm[key]`` после операции вернёт изменённое значение.

    Именно этим функция отличается от ``cm[key] = value``: тот пишет только в
    верхний слой.

    Подсказка: обойдите ``cm.maps`` и делайте ``layer[key] = value`` под
    условием ``if key in layer``. Обходить нужно ``maps``, а не ``cm``: через
    ``cm`` ключ виден всегда, и проверка потеряла бы смысл.
    """
