"""Упражнение 21. Найди баг: LRU-кэш. Уровень 5.

Перед вами реализация LRU-кэша на ``OrderedDict``. Она выглядит правильно,
проходит простые тесты, но содержит **три бага**. Ваша задача — исправить код
(можно менять любую строку), не переписывая структуру заново.

Как искать: прогоните тесты (``uv run pytest -k ex21``), прочитайте падения,
сформулируйте гипотезу. Но главное — подумайте о сценариях, которые тесты
могут не покрывать: обновление существующего ключа, ``get`` по отсутствующему
ключу, порядок вытеснения после серии обращений.

Подсказки к стилю багов в этом упражнении (без деталей):

* один баг связан с тем, что обращение к ключу обязано «освежать» его;
* один баг связан с тем, чего класс не должен позволять;
* один баг связан с путаницей краёв ``OrderedDict`` (``last=True``/``False``).

Определение LRU (см. упражнение 9): при каждом обращении (``get`` и ``put``
существующего) ключ перемещается в конец порядка вытеснения; при переполнении
вытесняется ключ из начала.
"""

from __future__ import annotations

from collections import OrderedDict


class BuggyLRUCache:
    """Кэш с тремя багами: найдите и исправьте их.

    Класс уже реализован, но в нём три дефекта. Тесты падают; почитайте
    трейсбеки и всмотритесь в код. Менять можно всё, но решение в одну-две
    строки на баг.
    """

    def __init__(self, capacity: int) -> None:
        """Создать кэш на ``capacity`` элементов."""
        self.capacity = capacity
        self._data: OrderedDict[str, int] = OrderedDict()

    def get(self, key: str) -> int | None:
        """Вернуть значение по ключу, освежив его (или ``None``)."""
        if key in self._data:
            return self._data[key]
        return None

    def put(self, key: str, value: int) -> None:
        """Записать пару; при переполнении вытеснить самого старого."""
        self._data[key] = value
        if len(self._data) > self.capacity:
            self._data.popitem(last=True)

    def __len__(self) -> int:
        """Число записей в кэше."""
        return len(self._data)
