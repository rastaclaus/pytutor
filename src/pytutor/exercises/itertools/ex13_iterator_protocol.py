def is_iterator(value: object) -> bool:
    """Проверить, что объект — итератор, а не просто итерируемое.

    ``is_iterator(iter([1]))`` -> ``True``;
    ``is_iterator(value for value in [1])`` -> ``True``;
    ``is_iterator([1])`` -> ``False``;
    ``is_iterator("abc")`` -> ``False`` — строка итерируема, но не итератор;
    ``is_iterator(42)`` -> ``False`` — не итерируемое вовсе, ошибки быть не
    должно.

    Подсказка: у итератора есть и ``__iter__``, и ``__next__``; короткий
    признак — ``iter(value) is value``. Для не-итерируемых ``iter`` бросит
    ``TypeError``, поэтому проверьте ``hasattr(value, "__iter__")`` заранее.
    """
    raise NotImplementedError


